class TestSearch:
    """Search by title/abstract/author."""

    def test_search_by_title(self, client: ZoteroClient) -> None:
        results = client.search("Transformer")
        assert len(results) >= 1
        assert any("Transformer" in r["title"] for r in results)

    def test_search_by_author_last_name(self, client: ZoteroClient) -> None:
        results = client.search("Doe")
        assert len(results) >= 1
        assert any("Doe" in r["authors"] for r in results)

    def test_search_by_abstract(self, client: ZoteroClient) -> None:
        results = client.search("comprehensive survey")
        assert any("Neural Network" in r["title"] for r in results)

    def test_search_filters_by_collection(self, client: ZoteroClient) -> None:
        results = client.search("Neural", collection_key="COLL001")
        assert len(results) >= 1

    def test_search_filters_by_tag(self, client: ZoteroClient) -> None:
        results = client.search("Neural", tag="machine-learning")
        assert len(results) >= 1

    def test_search_respects_limit(self, client: ZoteroClient) -> None:
        results = client.search("paper", limit=2)
        assert len(results) <= 2

    def test_search_no_match_returns_empty(self, client: ZoteroClient) -> None:
        results = client.search("QuantumGravity")
        assert results == []


class TestGetItem:
    """Full metadata retrieval."""

    def test_get_item_returns_full_metadata(self, client: ZoteroClient) -> None:
        item = client.get_item("ABCD1234")
        assert item["key"] == "ABCD1234"
        assert item["title"] == "Neural Network Survey Paper"
        assert item["doi"] == "10.1234/jmlr.2024.001"
        assert item["item_type"] == "journalArticle"
        assert len(item["authors"]) == 2
        assert len(item["tags"]) == 2

    def test_get_item_authors_ordered(self, client: ZoteroClient) -> None:
        item = client.get_item("ABCD1234")
        # First author by orderIndex=0
        assert item["authors"][0]["lastName"] == "Doe"
        assert item["authors"][1]["lastName"] == "Smith"

    def test_get_item_includes_attachments(self, client: ZoteroClient) -> None:
        item = client.get_item("ABCD1234")
        assert len(item["attachments"]) == 1
        assert item["attachments"][0]["contentType"] == "application/pdf"

    def test_get_item_includes_collections(self, client: ZoteroClient) -> None:
        item = client.get_item("ABCD1234")
        keys = [c["key"] for c in item["collections"]]
        assert "COLL001" in keys
        assert "COLL002" in keys

    def test_get_item_includes_notes(self, client: ZoteroClient) -> None:
        item = client.get_item("ABCD1234")
        assert len(item["notes"]) == 1
        assert "p. 5" in item["notes"][0]["note"]

    def test_get_item_unknown_key_raises(self, client: ZoteroClient) -> None:
        with pytest.raises(ZoteroItemNotFoundError):
            client.get_item("DOESNOTEXIST")


