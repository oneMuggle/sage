class TestReadPdfFulltext:
    """PDF full-text reading."""

    def test_read_pdf_returns_indexed_text(self, client: ZoteroClient) -> None:
        result = client.read_pdf_fulltext("ABCD1234")
        assert result["source"] == "index"
        assert "neural" in result["chunk_text"]
        assert "model" in result["chunk_text"]

    def test_read_pdf_reports_total_chars(self, client: ZoteroClient) -> None:
        result = client.read_pdf_fulltext("ABCD1234")
        assert result["total_chars"] > 0

    def test_read_pdf_chunks_at_offset(self, client: ZoteroClient) -> None:
        first = client.read_pdf_fulltext("ABCD1234", chunk_offset=0)
        result = client.read_pdf_fulltext("ABCD1234", chunk_offset=5)
        assert result["chunk_offset"] == 5
        # chunk_offset indicates where reading starts in the full text
        assert result["chunk_text"] == first["chunk_text"][5:]

    def test_read_pdf_reports_unavailable_for_unindexed(
        self, client: ZoteroClient
    ) -> None:
        result = client.read_pdf_fulltext("BOOK0001")
        assert result["source"] in ("file", "unavailable")

    def test_read_pdf_unknown_item_raises(self, client: ZoteroClient) -> None:
        with pytest.raises(ZoteroItemNotFoundError):
            client.read_pdf_fulltext("DOESNOTEXIST")


