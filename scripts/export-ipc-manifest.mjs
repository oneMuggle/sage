#!/usr/bin/env node
/**
 * Export the IPC command -> backend route manifest.
 *
 *   node scripts/export-ipc-manifest.mjs          rewrite electron/ipc-manifest.json
 *   node scripts/export-ipc-manifest.mjs --check  exit 1 when the committed manifest is stale
 *
 * The single source of truth is electron/commands.ts (COMMAND_ROUTES, including the domain tables
 * under electron/commandRoutes/ it spreads in). The manifest is the same table as plain data —
 * (method, path template) per command — so the backend contract test can check it against the
 * real FastAPI app. electron/__tests__/ipc-contract.test.ts fails when it is stale.
 *
 * TypeScript is evaluated with the compiler's own transpileModule plus a tiny CommonJS loader:
 * no bundler and no extra dependency. The loader refuses package imports on purpose — route
 * modules must stay pure.
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import vm from 'node:vm';
import ts from 'typescript';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const MANIFEST_PATH = join(ROOT, 'electron', 'ipc-manifest.json');
const COMMENT =
  'Generated by scripts/export-ipc-manifest.mjs from electron/commands.ts ' +
  '(+ electron/commandRoutes/*). Do not edit by hand: run `npm run ipc:manifest`. ' +
  'One (method, path template) per renderer invoke() command; query strings are dropped.';

function resolveTs(fromDir, spec) {
  const base = resolve(fromDir, spec);
  for (const candidate of [`${base}.ts`, join(base, 'index.ts')]) {
    if (existsSync(candidate)) return candidate;
  }
  throw new Error(`cannot resolve "${spec}" from ${fromDir}`);
}

/** Evaluate a TypeScript module graph that consists of relative imports only. */
function loadTsModule(entry) {
  const cache = new Map();
  const load = (file) => {
    const hit = cache.get(file);
    if (hit) return hit.exports;
    const js = ts.transpileModule(readFileSync(file, 'utf-8'), {
      compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 },
      fileName: file,
    }).outputText;
    const mod = { exports: {} };
    cache.set(file, mod);
    const localRequire = (spec) => {
      if (!spec.startsWith('.')) {
        throw new Error(
          `${file} imports package "${spec}": IPC route modules must stay pure (relative imports only)`,
        );
      }
      return load(resolveTs(dirname(file), spec));
    };
    const run = vm.runInThisContext(
      `(function (exports, require, module, __filename, __dirname) {${js}\n})`,
      { filename: file },
    );
    run(mod.exports, localRequire, mod, file, dirname(file));
    return mod.exports;
  };
  return load(entry);
}

/** One entry per line keeps the file reviewable and diffs minimal. */
function serialize(manifest) {
  const rows = Object.entries(manifest).map(
    ([cmd, e]) =>
      `    ${JSON.stringify(cmd)}: { "method": ${JSON.stringify(e.method)}, "path": ${JSON.stringify(e.path)} }`,
  );
  return `{\n  "_comment": ${JSON.stringify(COMMENT)},\n  "commands": {\n${rows.join(',\n')}\n  }\n}\n`;
}

const { COMMAND_ROUTES } = loadTsModule(join(ROOT, 'electron', 'commands.ts'));
const { buildIpcManifest } = loadTsModule(join(ROOT, 'electron', 'ipcManifest.ts'));
const manifest = buildIpcManifest(COMMAND_ROUTES);
const next = serialize(manifest);
const count = Object.keys(manifest).length;

if (process.argv.includes('--check')) {
  // Compare ignoring line endings: Windows checkouts may carry CRLF.
  const current = existsSync(MANIFEST_PATH) ? readFileSync(MANIFEST_PATH, 'utf-8') : '';
  if (current.replace(/\r\n/g, '\n') !== next) {
    console.error('electron/ipc-manifest.json is stale. Run `npm run ipc:manifest` and commit it.');
    process.exit(1);
  }
  console.log(`electron/ipc-manifest.json is up to date (${count} commands).`);
} else {
  writeFileSync(MANIFEST_PATH, next);
  console.log(`Wrote electron/ipc-manifest.json (${count} commands).`);
}
