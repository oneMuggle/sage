#!/usr/bin/env node
/**
 * Regenerate the bundled dafeiyu pack manifest from the WebM files.
 *
 * Usage: node scripts/pet-pack/generate-dafeiyu-pack.mjs
 *
 * The upstream dsh-pet config.jsonc classifies 109 animations; this script
 * mirrors the Sage subset: work-status / clicks / sleep / drag / retry are
 * explicit events, everything else becomes an idle/random pool.
 */

import { readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const dir = 'public/pet/dafeiyu';
const files = readdirSync(dir)
  .filter((name) => name.endsWith('.webm'))
  .sort((a, b) => a.localeCompare(b, 'zh'));

function many(...names) {
  return names.map((name) => `${name}.webm`).filter((file) => files.includes(file));
}

const clicks = many(
  '点击回应-开心跃动',
  '点击回应-害羞惊讶',
  '点击回应-傲娇生气',
  '点击回应-挠痒咯咯笑',
  '点击回应-元气挥手',
);
const workStatus = many(
  '工作状态-思考冒泡',
  '工作状态-忙碌点按',
  '工作状态-清点归档',
  '工作状态-原地踱步张望',
  '工作状态-雀跃庆祝',
  '工作状态-垂头叹气冒汗',
);
const sleep = many('睡觉-开始', '睡觉-循环', '睡觉-起来');
const balance = many(
  '余额-钱袋满溢',
  '余额-金袋叮当',
  '余额-钱袋如常',
  '余额-数金皱眉',
  '余额-袋空如洗',
  '余额-分文不剩',
);
const drag = many('被鼠标拖拽悬空反馈');
const retry = many('深度思考碎碎念');

const eventFiles = new Set([...clicks, ...workStatus, ...sleep, ...balance, ...drag, ...retry]);
const preferredIdle = ['待机呼吸休闲.webm', '东张西望.webm'].filter((file) => files.includes(file));
const idle = [
  ...preferredIdle,
  ...files.filter((file) => !eventFiles.has(file) && !preferredIdle.includes(file)),
];

const actions = {
  idle,
  thinking: many('工作状态-思考冒泡'),
  acting: many('工作状态-忙碌点按'),
  acting_edit: many('写代码'),
  acting_read: many('工作状态-清点归档'),
  acting_web: many('工作状态-原地踱步张望'),
  observing: many('工作状态-原地踱步张望'),
  retry,
  waiting: many('点击回应-害羞惊讶'),
  done: many('工作状态-雀跃庆祝'),
  error: many('工作状态-垂头叹气冒汗'),
  click: clicks,
  pat: many('点击回应-挠痒咯咯笑'),
  angry: many('点击回应-傲娇生气'),
  drag,
  sleep_start: many('睡觉-开始'),
  sleep_loop: many('睡觉-循环'),
  sleep_end: many('睡觉-起来'),
  balance,
};

const pack = {
  id: 'dafeiyu',
  name: '大肥鱼',
  version: '0.3.8',
  license: 'MIT',
  source: 'https://github.com/PC2005-cloud/dsh-pet',
  canvas: { width: 640, height: 360 },
  anchor: { x: 320, y: 330 },
  actions,
};

writeFileSync(join(dir, 'pack.json'), `${JSON.stringify(pack, null, 2)}\n`, 'utf8');
writeFileSync(
  'src/pet/engine/packs.ts',
  `/**
 * Built-in pet packs — generated by scripts/pet-pack/generate-dafeiyu-pack.mjs.
 *
 * Bundled as a module instead of fetched from public/<id>/pack.json: the
 * packaged renderer loads file://.../dist/pet.html, where fetch() on a
 * sibling file can be blocked by CORS.
 */

import type { PetPack } from './animation';

export const DAFEIYU_PACK: PetPack = ${JSON.stringify(pack, null, 2)};

export function packFor(id: string): PetPack | null {
  return id === DAFEIYU_PACK.id ? DAFEIYU_PACK : null;
}
`,
  'utf8',
);

console.log(
  `dafeiyu pack: ${files.length} files, idle=${idle.length}, clicks=${clicks.length}, work=${workStatus.length}`,
);
